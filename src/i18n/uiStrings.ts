export function getUiString(
  language: LanguageCode,
  key: UiStringKey,
  params?: Record<string, string | number>
): string {
  const dictionary = UI_STRINGS[language] || UI_STRINGS.en
  let value = dictionary[key] || UI_STRINGS.en[key]

  if (params) {
    Object.entries(params).forEach(([param, replacement]) => {
      value = value.replace(
        new RegExp(`\\{${param}\\}`, 'g'),
        String(replacement)
      )
    })
  }

  return value
}
